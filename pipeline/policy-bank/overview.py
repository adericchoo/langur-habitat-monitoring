"""Plain-English overview of a policy-bank run, built from templates.

Every sentence is assembled from fields the run already holds: the scorer's
counts and tiers, each case's curated plain_name and plain_use, the grade, and
the status of each precondition. Nothing is generated by a model, so the same
run always gives the same overview, and each clause traces to a field.

An option's name links to its main source (the first source listed for the
case), so a reader can go straight to the policy.

    site_overview(brief, cfg)          one paragraph per site brief (Markdown)
    run_overview(briefs, not_briefed, scored, cfg)
                                       the run-level opening paragraph (Markdown)
    plain_text(markdown)               the same text with links removed, for the terminal
"""
import re
from collections import Counter

NUMBER_WORDS = {1: "one", 2: "two", 3: "three", 4: "four", 5: "five", 6: "six",
                7: "seven", 8: "eight", 9: "nine", 10: "ten"}
MAX_CONDITIONS = 2   # conditions named per "confirm" sentence before "and N more"


def number(n):
    return NUMBER_WORDS.get(n, str(n))


def cap(text):
    return text[:1].upper() + text[1:]


def lower_first(text):
    """Lower-case the first letter unless the first word is an acronym or proper noun."""
    first = text.split(" ", 1)[0]
    if first.isupper() or first in ("India's", "Vietnam's", "Ninh", "Kim", "Van"):
        return text
    return text[:1].lower() + text[1:]


def join(items):
    """Joins a list for a sentence; uses semicolons when an item has its own comma."""
    items = list(items)
    if len(items) <= 1:
        return "".join(items)
    if any("," in i for i in items):
        return "; ".join(items[:-1]) + "; and " + items[-1]
    return ", ".join(items[:-1]) + " and " + items[-1]


def linked(name, option):
    """The option's plain name as a Markdown link to its main source."""
    sources = option.get("sources") or []
    return f"[{name}]({sources[0]['url']})" if sources else name


def option_sentence(o, seen=None):
    """One sentence on one matched option, worded by its grade.

    `seen` holds (case, grade) pairs already described for this site; a repeat
    gets a short sentence pointing back instead of the full one.
    """
    key = (o["case_id"], o["grade"])
    if seen is not None and key in seen:
        if o["grade"] == "in_place":
            return f"{cap(o['plain_home_name'])} covers these patches too."
        return f"{cap(o['plain_name'])} applies to these patches too, on the same conditions."
    if seen is not None:
        seen.add(key)
    if o["grade"] == "in_place":
        return f"{linked(cap(o['plain_home_name']), o)} is already in place here, so {o['plain_home_check']}."
    name = linked(cap(o["plain_name"]), o)
    if o["grade"] == "ready":
        return f"{name} {o['plain_use']}, and every condition for it holds here, so it can be raised now."
    if o["grade"] == "groundwork":
        failed = [c["text"] for c in o["conditions"] if c["status"] == "not_met"]
        conds = join(f'"{lower_first(t)}"' for t in failed)
        return (f"{name} {o['plain_use']}, but it needs groundwork first: "
                f"{'the condition' if len(failed) == 1 else 'the conditions'} {conds} "
                f"{'is' if len(failed) == 1 else 'are'} not met here.")
    open_ = [c["text"] for c in o["conditions"] if c["status"] in ("unknown", "partial")]
    shown = [f"that {lower_first(t)}" for t in open_[:MAX_CONDITIONS]]
    more = len(open_) - len(shown)
    tail = f", and {number(more)} more condition{'s' if more > 1 else ''} in the brief" if more > 0 else ""
    return f"{name} {o['plain_use']}; before raising it, confirm {join(shown)}{tail}."


def group_label(facts, cfg):
    label = cfg["protected_labels"].get(facts["g_protected"], "with protection status not known")
    if facts.get("g_designation") not in ("", "none", None) and facts["g_protected"] == "inside":
        label += f" ({facts['g_designation']})"
    return label


def patch_noun(brief, cfg):
    drivers = {g["facts"]["driver"] for g in brief["groups"]}
    if len(drivers) == 1:
        return cfg["driver_patch_noun"][drivers.pop()]
    return "suspected forest-loss patches"


def tier_clause(by_tier):
    if by_tier.get("P1"):
        n = by_tier["P1"]
        return f"{number(n)} of them {'is' if n == 1 else 'are'} in the top priority tier"
    if by_tier.get("P2"):
        return "the highest-ranked is in the middle priority tier"
    return "all of them are in the lowest priority tier"


def site_overview(brief, cfg):
    """The site's paragraph: what was flagged, then each group's options."""
    p = brief["patches"]
    area = f", {p['area_ha']} ha in total" if p.get("area_ha") is not None else ""
    parts = [f"**{brief['site_name']}** has {p['count']} {patch_noun(brief, cfg)}{area}; "
             f"{tier_clause(p['by_tier'])}."]
    groups = brief["groups"]
    per_group = cfg["overview_options_per_group"]
    seen = set()
    if len(groups) == 1:
        opts = groups[0]["options"][:cfg["overview_options_single"]]
        parts += [option_sentence(o, seen) for o in opts] or [
            "No case in the bank applies to these patches yet."]
    else:
        split = [f"{g['patch_count']} {group_label(g['facts'], cfg)}" for g in groups]
        split[0] = split[0].replace(" ", f" {'lies' if groups[0]['patch_count'] == 1 else 'lie'} ", 1)
        parts.append(f"Of these, {join(split)}, and the options differ between them.")
        for g in groups:
            opts = g["options"][:per_group]
            noun = "patch" if g["patch_count"] == 1 else "patches"
            lead = f"For the {g['patch_count']} {noun} {group_label(g['facts'], cfg)}:"
            if not opts:
                parts.append(f"{lead} no case in the bank applies yet.")
                continue
            sentences = [option_sentence(o, seen) for o in opts]
            parts.append(f"{lead} {sentences[0]}")
            parts += sentences[1:]
    return " ".join(parts)


def run_overview(briefs, not_briefed, scored, cfg, site_names):
    """The run-level opening: what was scored, which sites are briefed, how ready the options are."""
    tiers = Counter(r["tier"] for r in scored)
    sites = {r["site_id"] for r in scored}
    year = scored[0]["run_year"] if scored else ""
    tier_bits = [f"{tiers.get('P1', 0)} in the top priority tier",
                 f"{tiers.get('P2', 0)} in the middle", f"{tiers.get('P3', 0)} in the lowest"]
    if tiers.get("unscored"):
        tier_bits.append(f"{tiers['unscored']} that could not be scored")
    out = [f"This run ({year}) scored {len(scored)} suspected forest-loss patches across "
           f"{len(sites)} sites: {join(tier_bits)}."]

    briefed = [f"{b['site_name']} ({b['patches']['count']} patches, top priority {b['top_priority']})"
               for b in briefs]
    out.append(f"The {number(len(briefs))} sites with the highest-ranked patches are briefed: "
               f"{join(briefed)}.")
    if not_briefed["sites"]:
        others = join(site_names.get(s, s) for s in not_briefed["sites"])
        out.append(f"The other {number(len(not_briefed['sites']))} sites ({others}) hold the remaining "
                   f"{not_briefed['count']} patches and are not briefed this run.")

    options = [o for b in briefs for g in b["groups"] for o in g["options"]]
    if options and not any(o["grade"] == "ready" for o in options):
        out.append("No option is ready to raise outright yet: each one still has a condition to "
                   "confirm or is already in place and needs checking.")
    if options and not any(o["reviewed_by_svw"] for o in options):
        out.append("None of the cases has been reviewed by Save Vietnam's Wildlife yet.")
    return " ".join(out)


def plain_text(markdown):
    """Strips Markdown links and bold for terminal output."""
    text = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", markdown)
    return text.replace("**", "")
